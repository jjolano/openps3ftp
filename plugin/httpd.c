opftp_httpd_t* opftp_httpd_create(opftp_server_t* s, const char* version,
                                  uint16_t port, const char* asset_dir)
{
    opftp_httpd_t* h = calloc(1, sizeof(*h));
    if (!h) return NULL;
    h->server = s;
    h->port = port ? port : HTTPD_PORT_DEFAULT;
    strncpy(h->version, version ? version : "?", sizeof(h->version) - 1);
#ifndef OPFTP_PS3
    if (asset_dir)
        strncpy(h->asset_dir, asset_dir, sizeof(h->asset_dir) - 1);
#endif
    for (int k = 0; k < HTTPD_MAX_CONN; k++)
        h->conn_fd[k] = -1;

    h->poll = opftp_pollset_create();
    if (!h->poll) { free(h); return NULL; }

    h->listen_fd = socket(AF_INET, SOCK_STREAM, 0);
    if (h->listen_fd < 0) { opftp_pollset_destroy(h->poll); free(h); return NULL; }
    int one = 1;
    setsockopt(h->listen_fd, SOL_SOCKET, SO_REUSEADDR, &one, sizeof(one));

    struct sockaddr_in sa;
    memset(&sa, 0, sizeof(sa));
    sa.sin_family = AF_INET;
    sa.sin_port = htons(h->port);
    sa.sin_addr.s_addr = htonl(INADDR_ANY);
    if (bind(h->listen_fd, (struct sockaddr*)&sa, sizeof(sa)) != 0 ||
        listen(h->listen_fd, 4) != 0) {
        opftp_close_fd(h->listen_fd);
        opftp_pollset_destroy(h->poll);
        free(h);
        return NULL;
    }
    /* non-blocking listener so the accept drain loop can stop at
     * EAGAIN (same as the FTP reactor's listener) */
    opftp_set_nonblock(h->listen_fd);
    opftp_pollset_add(h->poll, h->listen_fd, POLLIN, (void*)(intptr_t)h->listen_fd);

    h->thread = opftp_thread_create(httpd_thread, h);
    if (h->thread == NULL) {
        opftp_close_fd(h->listen_fd);
        opftp_pollset_destroy(h->poll);
        free(h);
        return NULL;
    }
    return h;
}

void opftp_httpd_destroy(opftp_httpd_t* h)
{
    if (!h) return;
    h->stop = true;
    opftp_pollset_wake(h->poll);
    opftp_thread_join(h->thread);   /* free only after the thread exits */
    opftp_thread_destroy(h->thread);
    opftp_close_fd(h->listen_fd);
    opftp_pollset_destroy(h->poll);
    free(h);
}
